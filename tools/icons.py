# Small plane icons for wide ranges (paste icons.h into src/c/flight_radar.c): hand-checked base frames for 0, 22.5 and 45 degrees,
# the other 13 headings come from exact 90-degree rotations and a diagonal mirror.
import sys
from PIL import Image
N = 11
BASE = {
'JET': ["""
.....#.....
....###....
....###....
....###....
....###....
..#######..
.#########.
###.###.###
....###....
....###....
...#####...
""", """
.......#...
......##...
......##...
.....##....
.######....
########...
....####...
....#####..
...##..###.
.####....#.
....##.....
""", """
...........
.........#.
........##.
.......###.
##....###..
.########..
..######...
...####....
#.###.##...
.##....##..
..#.....#..
"""],
}
def parse(s): return [[c == '#' for c in line] for line in s.strip().split('\n')]
def rot90(g): return [[g[N-1-x][y] for x in range(N)] for y in range(N)]       # clockwise
def mirror(g): return [[g[N-1-x][N-1-y] for x in range(N)] for y in range(N)]  # across NE diagonal
def frames(name):
    b = [parse(s) for s in BASE[name]]
    q = [b[0], b[1], b[2], mirror(b[1])]          # 0, 22.5, 45, 67.5
    out = []
    for r in range(4):
        out += q
        q = [rot90(g) for g in q]
    return out
def bits(g): return [sum(1 << x for x in range(N) if g[y][x]) for y in range(N)]
if __name__ == '__main__':
    sc = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    names = ['JET']
    im = Image.new('RGB', (16*(N+4)*sc, len(names)*(N+4)*sc), (0, 0, 0))
    for r, nm in enumerate(names):
        for k, g in enumerate(frames(nm)):
            for y in range(N):
                for x in range(N):
                    if g[y][x]:
                        for i in range(sc):
                            for j in range(sc):
                                im.putpixel(((k*(N+4)+2+x)*sc+i, (r*(N+4)+2+y)*sc+j), (120, 230, 180))
    im.save('icons_preview.png')
    with open('icons.h', 'w') as f:
        f.write('// Generated by tools/icons.py: [heading/22.5][row], bit x = column x, 11x11 centered on (5,5).\n')
        for nm in names:
            f.write('static const uint16_t %s_S_BITS[16][%d] = {\n' % (nm, N))
            for g in frames(nm):
                f.write('  {' + ', '.join('0x%03x' % v for v in bits(g)) + '},\n')
            f.write('};\n')
